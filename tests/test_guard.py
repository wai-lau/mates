import json, pytest
import guard

def d(path, added=(), removed=()):
    body = "".join(f"-{l}\n" for l in removed) + "".join(f"+{l}\n" for l in added)
    return f"diff --git a/{path} b/{path}\n--- a/{path}\n+++ b/{path}\n@@ -1 +1 @@\n{body}"

def test_clean_diff_no_flags():
    assert guard.guard_flags(d("src/a.py", ["x = 1"], ["x = 0"]), ["src/a.py"]) == []

def test_flag_unnamed_file():
    assert "unnamed-file:src/b.py" in guard.guard_flags(d("src/b.py", ["y = 2"]), ["src/a.py"])

def test_flag_test_file():
    f = guard.guard_flags(d("tests/test_a.py", ["def test_x(): pass"]), ["tests/test_a.py"])
    assert "test-file:tests/test_a.py" in f

def test_flag_skip_added():
    f = guard.guard_flags(d("tests/test_a.py", ["@pytest.mark.skip"]), ["tests/test_a.py"])
    assert "test-skipped:tests/test_a.py" in f

def test_flag_assertion_removed():
    f = guard.guard_flags(d("tests/test_a.py", [], ["    assert x == 1"]), ["tests/test_a.py"])
    assert "assertion-removed:tests/test_a.py" in f

def test_flag_mates_dir():
    assert "mates-dir:.mates/check.sh" in guard.guard_flags(d(".mates/check.sh", ["exit 0"]), [".mates/check.sh"])

def test_flag_authorship():
    assert "authorship:src/a.py" in guard.guard_flags(d("src/a.py", ["# generated by Qwen"]), ["src/a.py"])

def test_deleted_file_counts():
    diff = "diff --git a/src/c.py b/src/c.py\ndeleted file mode 100644\n--- a/src/c.py\n+++ /dev/null\n@@ -1 +0,0 @@\n-z = 3\n"
    assert "unnamed-file:src/c.py" in guard.guard_flags(diff, ["src/a.py"])

def test_redact_keeps_rest():
    out = guard.redact_authorship(d("src/a.py", ["# written by Qwen"]))
    assert "+# written by [redacted]" in out and "Qwen" not in out

def test_load_brief_rejects_empty_files(tmp_path):
    p = tmp_path / "b.json"; p.write_text(json.dumps({"goal": "g", "files": [], "constraints": ""}))
    with pytest.raises(ValueError): guard.load_brief(p)

def test_load_brief_ok(tmp_path):
    p = tmp_path / "b.json"; p.write_text(json.dumps({"goal": "g", "files": ["a"], "constraints": ""}))
    assert guard.load_brief(p)["files"] == ["a"]

def test_guard_flags_hook_paths():
    for path in (".githooks/pre-commit", ".husky/pre-push", "tools/hooks/post-merge", ".gitattributes",
                 "sub/.gitignore", ".gitmodules"):
        f = guard.guard_flags(d(path, ["x"]), [path], hooks_path="./tools/hooks/")
        assert f"hook-path:{path}" in f, path
    assert guard.guard_flags(d("src/hooks.py", ["x"]), ["src/hooks.py"], hooks_path="tools/hooks") == []
    assert guard.guard_flags(d("tools/hooks/x", ["x"]), ["tools/hooks/x"]) == []  # no hooksPath given
    assert guard.guard_flags(d("x", ["x"]), ["x"], hooks_path="/abs/hooks") == []  # outside the repo

def test_guard_flags_manifests():
    for path in ("pyproject.toml", "uv.lock", "requirements.txt", "requirements-dev.txt", "web/package.json",
                 "package-lock.json", "Cargo.toml", "crates/a/Cargo.lock", "deps/locked.txt"):
        f = guard.guard_flags(d(path, ["x"]), [path], runtime_files=[".mates/runtime.sh", "deps/locked.txt"])
        assert f"runtime-input:{path}" in f, path
    assert guard.guard_flags(d("src/package.py", ["x"]), ["src/package.py"]) == []

def test_guard_flags_binary_file_counts():
    diff = ("diff --git a/.githooks/pre-commit b/.githooks/pre-commit\nnew file mode 100755\n"
            "index 0000000..1111111\nBinary files /dev/null and b/.githooks/pre-commit differ\n")
    assert "hook-path:.githooks/pre-commit" in guard.guard_flags(diff, [".githooks/pre-commit"])

def test_guard_hunk_line_cannot_rename_file():
    diff = d(".githooks/pre-commit", ["+ b/innocent.py", "evil"])  # an added `++ b/innocent.py` line
    f = guard.guard_flags(diff, ["innocent.py"])
    assert "hook-path:.githooks/pre-commit" in f and not any("innocent.py" in x for x in f)

def test_guard_quoted_paths():
    # git quotes non-ASCII names; a binary file has no ---/+++ lines, so the header is all there is
    binary = ('diff --git "a/.githooks/caf\\303\\251" "b/.githooks/caf\\303\\251"\nnew file mode 100755\n'
              'Binary files /dev/null and "b/.githooks/caf\\303\\251" differ\n')
    assert "hook-path:.githooks/café" in guard.guard_flags(binary, [])
    text = ('diff --git "a/tests/test_\\"q\\".py" "b/tests/test_\\"q\\".py"\n'
            '--- "a/tests/test_\\"q\\".py"\n+++ "b/tests/test_\\"q\\".py"\n@@ -1 +1 @@\n+@pytest.mark.skip\n')
    f = guard.guard_flags(text, [])
    assert 'test-skipped:tests/test_"q".py' in f and 'unnamed-file:tests/test_"q".py' in f


