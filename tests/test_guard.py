import json, pytest
import guard

def d(path, added=(), removed=()):
    body = "".join(f"-{l}\n" for l in removed) + "".join(f"+{l}\n" for l in added)
    return f"diff --git a/{path} b/{path}\n--- a/{path}\n+++ b/{path}\n@@ -1 +1 @@\n{body}"

def test_clean_diff_no_flags():
    assert guard.guard_flags(d("src/a.py", ["x = 1"], ["x = 0"]), ["src/a.py"]) == []

def test_flag_unnamed_file():
    assert "unnamed-file:src/b.py" in guard.guard_flags(d("src/b.py", ["y = 2"]), ["src/a.py"])

def test_flag_test_file():
    f = guard.guard_flags(d("tests/test_a.py", ["def test_x(): pass"]), ["tests/test_a.py"])
    assert "test-file:tests/test_a.py" in f

def test_flag_skip_added():
    f = guard.guard_flags(d("tests/test_a.py", ["@pytest.mark.skip"]), ["tests/test_a.py"])
    assert "test-skipped:tests/test_a.py" in f

def test_flag_assertion_removed():
    f = guard.guard_flags(d("tests/test_a.py", [], ["    assert x == 1"]), ["tests/test_a.py"])
    assert "assertion-removed:tests/test_a.py" in f

def test_flag_mates_dir():
    assert "mates-dir:.mates/check.sh" in guard.guard_flags(d(".mates/check.sh", ["exit 0"]), [".mates/check.sh"])

def test_flag_authorship():
    assert "authorship:src/a.py" in guard.guard_flags(d("src/a.py", ["# generated by Qwen"]), ["src/a.py"])

def test_deleted_file_counts():
    diff = "diff --git a/src/c.py b/src/c.py\ndeleted file mode 100644\n--- a/src/c.py\n+++ /dev/null\n@@ -1 +0,0 @@\n-z = 3\n"
    assert "unnamed-file:src/c.py" in guard.guard_flags(diff, ["src/a.py"])

def test_redact_keeps_rest():
    out = guard.redact_authorship(d("src/a.py", ["# written by Qwen"]))
    assert "+# written by [redacted]" in out and "Qwen" not in out

def test_load_brief_rejects_empty_files(tmp_path):
    p = tmp_path / "b.json"; p.write_text(json.dumps({"goal": "g", "files": [], "constraints": ""}))
    with pytest.raises(ValueError): guard.load_brief(p)

def test_load_brief_ok(tmp_path):
    p = tmp_path / "b.json"; p.write_text(json.dumps({"goal": "g", "files": ["a"], "constraints": ""}))
    assert guard.load_brief(p)["files"] == ["a"]
